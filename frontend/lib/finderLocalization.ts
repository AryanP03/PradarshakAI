// ── Localization Helper Functions ──────────────────────────────────────────

/**
 * Returns localized text for a purpose option ID.
 */
export function getLocalizedPurpose(id: string, lang: string): string {
  const translations = PURPOSE_TRANSLATIONS[id];
  if (!translations) return id;
  return translations[lang] || translations.hi || translations.en || id;
}

/**
 * Returns localized label and description for an education level ID.
 */
export function getLocalizedEducation(id: string, lang: string): LocalizedEducation {
  const translations = EDUCATION_TRANSLATIONS[id];
  if (!translations) {
    return { label: id, desc: '' };
  }
  return translations[lang] || translations.hi || translations.en || { label: id, desc: '' };
}

/**
 * Returns localized group heading for an occupation group.
 */
export function getLocalizedJobGroup(group: string, lang: string): string {
  const translations = JOB_GROUPS_TRANSLATIONS[group];
  if (!translations) return group;
  return translations[lang] || translations.hi || translations.en || group;
}

/**
 * Returns localized label for an occupation ID.
 */
export function getLocalizedJobOption(id: string, fallbackLabel: string, lang: string): string {
  const translations = JOB_OPTIONS_TRANSLATIONS[id];
  if (!translations) return fallbackLabel;
  return translations[lang] || translations.hi || translations.en || fallbackLabel;
}

/**
 * Returns localized name for an Indian state / UT.
 */
export function getLocalizedState(stateName: string, lang: string): string {
  if (lang === 'en') return stateName;
  const translations = STATE_TRANSLATIONS[stateName];
  if (!translations) return stateName;
  return translations[lang] || translations.hi || stateName;
}

